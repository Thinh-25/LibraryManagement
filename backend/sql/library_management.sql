BEGIN;

CREATE TABLE nguoi_dung (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ho_ten VARCHAR(100) NOT NULL CHECK (btrim(ho_ten) <> ''),
 email VARCHAR(150) NOT NULL,
 mat_khau_hash VARCHAR(255) NOT NULL,
 so_dien_thoai VARCHAR(15),
 vai_tro VARCHAR(20) NOT NULL CHECK (vai_tro IN ('ADMIN','THU_THU','DOC_GIA')),
 trang_thai BOOLEAN NOT NULL DEFAULT TRUE,
 ngay_tao TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 CONSTRAINT uq_nguoi_dung_email UNIQUE (email),
 CONSTRAINT ck_email_format CHECK (email ~* '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'),
 CONSTRAINT ck_sdt CHECK (so_dien_thoai IS NULL OR so_dien_thoai ~ '^[0-9+]{9,15}$')
);
CREATE UNIQUE INDEX uq_nguoi_dung_email_ci ON nguoi_dung (lower(email));

CREATE TABLE the_thu_vien (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nguoi_dung_id BIGINT NOT NULL UNIQUE REFERENCES nguoi_dung(id) ON DELETE RESTRICT,
 ma_the VARCHAR(20) NOT NULL UNIQUE,
 ngay_cap DATE NOT NULL DEFAULT CURRENT_DATE,
 ngay_het_han DATE NOT NULL,
 trang_thai VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (trang_thai IN ('ACTIVE','EXPIRED','BLOCKED')),
 CONSTRAINT ck_han_the CHECK (ngay_het_han > ngay_cap)
);
CREATE TABLE the_loai (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ten_the_loai VARCHAR(100) NOT NULL UNIQUE,
 mo_ta VARCHAR(500)
);
CREATE TABLE tac_gia (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ho_ten VARCHAR(100) NOT NULL,
 tieu_su TEXT
);
CREATE TABLE nha_xuat_ban (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ten_nxb VARCHAR(150) NOT NULL UNIQUE,
 dia_chi VARCHAR(255),
 so_dien_thoai VARCHAR(15)
);
CREATE TABLE sach (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 isbn VARCHAR(20) UNIQUE,
 ten_sach VARCHAR(255) NOT NULL CHECK (btrim(ten_sach) <> ''),
 the_loai_id BIGINT NOT NULL REFERENCES the_loai(id) ON DELETE RESTRICT,
 nha_xuat_ban_id BIGINT NOT NULL REFERENCES nha_xuat_ban(id) ON DELETE RESTRICT,
 nam_xuat_ban INTEGER CHECK (nam_xuat_ban BETWEEN 1450 AND 2200),
 mo_ta TEXT,
 anh_bia VARCHAR(500),
 ngay_tao TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE sach_tac_gia (
 sach_id BIGINT NOT NULL REFERENCES sach(id) ON DELETE CASCADE,
 tac_gia_id BIGINT NOT NULL REFERENCES tac_gia(id) ON DELETE RESTRICT,
 PRIMARY KEY(sach_id,tac_gia_id)
);
CREATE TABLE cuon_sach (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 sach_id BIGINT NOT NULL REFERENCES sach(id) ON DELETE RESTRICT,
 ma_vach VARCHAR(50) NOT NULL UNIQUE,
 vi_tri_ke VARCHAR(100),
 tinh_trang VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE' CHECK (tinh_trang IN ('AVAILABLE','BORROWED','DAMAGED','LOST'))
);
CREATE TABLE phieu_muon (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 doc_gia_id BIGINT NOT NULL REFERENCES nguoi_dung(id) ON DELETE RESTRICT,
 thu_thu_id BIGINT NOT NULL REFERENCES nguoi_dung(id) ON DELETE RESTRICT,
 ngay_muon TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 ghi_chu VARCHAR(500)
);
CREATE TABLE chi_tiet_muon (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 phieu_muon_id BIGINT NOT NULL REFERENCES phieu_muon(id) ON DELETE RESTRICT,
 cuon_sach_id BIGINT NOT NULL REFERENCES cuon_sach(id) ON DELETE RESTRICT,
 han_tra TIMESTAMPTZ NOT NULL,
 ngay_tra TIMESTAMPTZ,
 trang_thai VARCHAR(20) NOT NULL DEFAULT 'BORROWED' CHECK (trang_thai IN ('BORROWED','RETURNED','LOST')),
 tinh_trang_khi_tra VARCHAR(100),
 CONSTRAINT ck_chi_tiet_tra CHECK (
    (trang_thai = 'RETURNED' AND ngay_tra IS NOT NULL) OR
    (trang_thai IN ('BORROWED','LOST') AND ngay_tra IS NULL)
 )
);
CREATE UNIQUE INDEX uq_cuon_dang_muon ON chi_tiet_muon(cuon_sach_id) WHERE trang_thai = 'BORROWED';
CREATE TABLE dat_truoc_sach (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 doc_gia_id BIGINT NOT NULL REFERENCES nguoi_dung(id) ON DELETE RESTRICT,
 sach_id BIGINT NOT NULL REFERENCES sach(id) ON DELETE RESTRICT,
 ngay_dat TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 ngay_het_han TIMESTAMPTZ,
 trang_thai VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (trang_thai IN ('PENDING','READY','COMPLETED','CANCELLED')),
 CONSTRAINT ck_dat_truoc_han CHECK (ngay_het_han IS NULL OR ngay_het_han > ngay_dat)
);
CREATE UNIQUE INDEX uq_dat_truoc_active ON dat_truoc_sach(doc_gia_id,sach_id) WHERE trang_thai IN ('PENDING','READY');
CREATE TABLE tien_phat (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 chi_tiet_muon_id BIGINT NOT NULL REFERENCES chi_tiet_muon(id) ON DELETE RESTRICT,
 ly_do VARCHAR(255) NOT NULL,
 so_tien NUMERIC(12,2) NOT NULL CHECK (so_tien > 0),
 trang_thai VARCHAR(20) NOT NULL DEFAULT 'UNPAID' CHECK (trang_thai IN ('UNPAID','PAID')),
 ngay_tao TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 ngay_thanh_toan TIMESTAMPTZ,
 CONSTRAINT ck_tien_phat_paid CHECK ((trang_thai = 'PAID' AND ngay_thanh_toan IS NOT NULL AND ngay_thanh_toan >= ngay_tao) OR (trang_thai = 'UNPAID' AND ngay_thanh_toan IS NULL))
);

CREATE INDEX idx_sach_ten ON sach(ten_sach);
CREATE INDEX idx_sach_the_loai ON sach(the_loai_id);
CREATE INDEX idx_sach_nxb ON sach(nha_xuat_ban_id);
CREATE INDEX idx_sach_tac_gia_tac_gia ON sach_tac_gia(tac_gia_id);
CREATE INDEX idx_cuon_sach_sach ON cuon_sach(sach_id);
CREATE INDEX idx_phieu_muon_doc_gia ON phieu_muon(doc_gia_id);
CREATE INDEX idx_phieu_muon_thu_thu ON phieu_muon(thu_thu_id);
CREATE INDEX idx_chi_tiet_muon_phieu ON chi_tiet_muon(phieu_muon_id);
CREATE INDEX idx_chi_tiet_muon_han ON chi_tiet_muon(han_tra) WHERE trang_thai='BORROWED';
CREATE INDEX idx_dat_truoc_sach ON dat_truoc_sach(sach_id);
CREATE INDEX idx_tien_phat_chi_tiet ON tien_phat(chi_tiet_muon_id);

